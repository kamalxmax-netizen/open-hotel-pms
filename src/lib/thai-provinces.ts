const THAI_PROVINCE_ALIASES: Array<{ alias: string; province: string }> = [
  { alias: "กท", province: "กรุงเทพมหานคร" },
  { alias: "กทม", province: "กรุงเทพมหานคร" },
];

export function suggestThaiProvinces(query: string, minChars = 2, limit = 20): string[] {
  const normalized = String(query || "").trim();
  if (normalized.length < minChars) return [];

  const startsWith = THAI_PROVINCES.filter((province) => province.startsWith(normalized));
  const contains = THAI_PROVINCES.filter(
    (province) => !province.startsWith(normalized) && province.includes(normalized)
  );
  const aliasMatches = THAI_PROVINCE_ALIASES.filter(
    ({ alias }) => alias.startsWith(normalized) || alias.includes(normalized)
  ).map((entry) => entry.province);

  return Array.from(new Set([...startsWith, ...contains, ...aliasMatches])).slice(0, limit);
}
